const dict: Record<Lang, Partial<Record<UIKey, string>>> = { ko, en, ja, zh };

/** Translator for one language; missing keys fall back to English, then Korean. */
export function useT(lang: Lang) {
  return (key: UIKey, vars: Record<string, string | number> = {}) => {
    let s = dict[lang][key] ?? en[key] ?? ko[key];
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export function isLang(x: string | undefined): x is Lang {
  return !!x && x in languages;
}
